import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const rootDirectory = dirname(dirname(fileURLToPath(import.meta.url)));
const entryPath = join(
  rootDirectory,
  "packages/core/src/audio-worklet-entry.ts",
);
const outputPath = join(
  rootDirectory,
  "packages/core/src/audio-worklet.generated.ts",
);

const result = await build({
  bundle: true,
  entryPoints: [entryPath],
  format: "iife",
  legalComments: "none",
  minify: true,
  platform: "browser",
  plugins: [
    {
      name: "exclude-generated-worklet",
      setup(build) {
        build.onResolve({ filter: /audio-worklet\.generated\.js$/ }, () => ({
          namespace: "generated-worklet",
          path: "source",
        }));
        build.onLoad({ filter: /.*/, namespace: "generated-worklet" }, () => ({
          contents: 'export const AUDIO_WORKLET_SOURCE = "";',
          loader: "js",
        }));
      },
    },
  ],
  target: "es2019",
  write: false,
});
const bundledSource = result.outputFiles[0]?.text.trim();
if (bundledSource === undefined || bundledSource.length === 0) {
  throw new Error("The AudioWorklet build produced no JavaScript.");
}

const generated = await format(
  `// Generated by scripts/generate-audio-worklet.mjs. Do not edit directly.\nexport const AUDIO_WORKLET_SOURCE = ${JSON.stringify(bundledSource)};\n`,
  { parser: "typescript" },
);

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "The generated AudioWorklet is stale. Run `pnpm generate:worklet`.",
    );
  }
} else {
  await writeFile(outputPath, generated);
}
